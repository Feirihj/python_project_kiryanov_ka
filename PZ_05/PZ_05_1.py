# C помощью функций получить вертикальную и горизонтальную линии.
# Линия проводится многократной печатью символа.
# Заключить слово в рамку из полученных линий.


def Ramka(word):
    # Определяем ширину рамки по длине переданного слова.
    length = len(word)

    # Внутренняя функция печатает горизонтальную линию из символов "#".
    def horlin(length):
        print("#"*(length+2))

    # Печатаем верхнюю линию, само слово и нижнюю линию рамки.
    horlin(length)
    print("#"+word+"#")
    horlin(length)

# Запрашиваем слово у пользователя.
while True:
    try:
        word = input("Введите слово: ")
    except:
        print("invalid input")
    Ramka(word)