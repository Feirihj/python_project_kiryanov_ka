# Дан список размера N. Осуществить циклический сдвиг элементов списка 
# вправо на одну позицию
import random
A = []
N = int(input("Введите размер списка: "))

while (N>0):
    A.append(random.randint(-100,100))
    N-=1

print(A)

size = len(A)
# Сохраняем последний элемент, который должен стать первым.
if size > 0:
    temp = A[size - 1]
    # Перемещаем элементы на одну позицию вправо.
    for i in range(size - 1, 0, -1):
        A[i] = A[i - 1]
    A[0] = temp

print(A)