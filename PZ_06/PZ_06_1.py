# Дан список А размера N. Вывести в начале его элементы с нечетными номерами в порядке возрастания номеров
# а затем - элементы с четными номерами в порядке убывания номеров
# УСЛОВНЫЙ ОПЕРАТОР НЕ ИСПОЛЬЗОВАТЬ
import random
A = []
N = int(input("Введите размер списка: "))
Na = N
Nb = Na

while (N>0):
    A.append(random.randint(0,100))
    N-=1

print(A)
# Выводим элементы с нечетными номерами по возрастанию номеров.
print("Нечетные по возрастанию: ")
while (Na>0):
    print(Nb-Na+1," > ", A[Nb-Na+1])
    Na-=2

# Выводим элементы с четными номерами в обратном порядке номеров.
print("Четные по убыванию: ")
while (Na<Nb):
    print(Nb-Na-2," > ", A[-(Na+2)])
    Na+=2