# Дан список А размера N. Сформировать 2 новых списка B и C:
# В список B записать все положительные элементы списка A, в Список C - все отрицательные (сохраняя последовательность)
# Вывести размер и содержимое списков

import random
A = []
N = int(input("Введите размер списка: "))

while (N>0):
    A.append(random.randint(-100,100))
    N-=1

B = []
C = []

# Положительные числа сохраняем в B, отрицательные — в C.
for i in range(0, len(A)):
    if (A[i]>0): B.append(A[i])
    if (A[i]<0): C.append(A[i])

# Выводим количество и содержимое каждого нового списка.
print(f"{len(B)} | {B}")
print(f"{len(C)} | {C}")